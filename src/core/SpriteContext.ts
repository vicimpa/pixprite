import type { LockFlags, MetaTarget } from "@pixprite/api";
import type { Bitmap, Rect } from "~/core/Image";
import type { Mask } from "~/core/Mask";
import type { TileRefs, Tileset } from "~/core/Tilemap";
import type { Placement } from "~/core/Transform";
import type { Sprite } from "./Sprite";
import type { Snapshot } from "./SpriteHistory";
import type { Cel, CelImage, ExtData, Floating, Layer, LockKind, SliceKey } from "./SpriteModel";

/** The mapped public view excludes private members; operations add the internal members they share. */
export type SpriteContext = Pick<Sprite, keyof Sprite> & {
  lastPaletteStep: number;
  floatingStart: number;
  lastMask: Mask | null;
  undoStack: Snapshot[];
  redoStack: Snapshot[];
  cache: Map<string, OffscreenCanvas>;
  cacheVersion: number;
  snapshot(label: string): Snapshot;
  restore(s: Snapshot): void;
  syncHistory(): void;
  refuse(kind: LockKind, op: keyof LockFlags): boolean;
  refuseSize(width: number, height: number): boolean;
  refuseFrameShift(at: number, count: number): boolean;
  extHolder(t: MetaTarget): { ext?: ExtData; } | null;
  replaceCel(l: Layer, frame: number, next: Cel): void;
  tilemapCels(t: number): CelImage[];
  commitTileset(t: number, ts: Tileset, remap?: ((ref: number) => number) | undefined): void;
  trimTiles(ts: Tileset, x: number, y: number, t: TileRefs): Cel;
  setTilemapCel(cel: Cel, layer: number, frame: number): void;
  editTiles(label: string, order: number[]): void;
  tilesFromPixels(ts: Tileset, tiles: Uint32Array<ArrayBufferLike>[], cel: CelImage): Cel;
  rebuildTilemaps(): void;
  filledCel(): CelImage;
  nextName(prefix: string): string;
  insertionPoint(): { index: number; depth: number; };
  moveBlock(a: number, b: number, before: number, depth: number, label: string): void;
  soloSaved: { layers: Layer[]; visible: boolean[]; } | null;
  mergeNodes(nodes: number[], label: string): void;
  flatten(frame: number, layers: number[], elastic?: boolean, vis?: (i: number) => boolean): Cel;
  insertFrames(at: number, count: number, make: (layer: Layer, li: number, k: number) => Cel, duration?: number): void;
  shiftTags(at: number, delta: number): void;
  nextSliceName(): string;
  selectedBitmap(layer?: number, frame?: number): { bmp: Bitmap; rect: Rect; shape: Uint8Array; };
  eraseSelection(): void;
  makeFloating(src: Bitmap, shape: Uint8Array<ArrayBufferLike>, place: Placement, layer?: number, frame?: number): Floating;
  setFloating(f: Floating | null): void;
  mergeFloating(f: Floating): Cel;
  mapAllCels(fn: (cel: CelImage, layer: Layer) => Cel): void;
  mapSliceKeys(fn: (k: SliceKey) => SliceKey): void;
  refitBackgrounds(): void;
  cropTo(r: Rect, label: string): void;
  drawLayer(ctx: OffscreenCanvasRenderingContext2D, index: number, frame: number, force?: boolean, override?: Uint32Array<ArrayBufferLike> | undefined, ox?: number, oy?: number): void;
  drawNode(ctx: OffscreenCanvasRenderingContext2D, i: number, frame: number, force?: boolean, override?: ((i: number) => Uint32Array | undefined) | undefined, ox?: number, oy?: number): void;
  drawSiblings(ctx: OffscreenCanvasRenderingContext2D, list: number[], frame: number, override?: ((i: number) => Uint32Array | undefined) | undefined, ox?: number, oy?: number, vis?: (i: number) => boolean): void;
  split: { sig: unknown[]; below: OffscreenCanvas; above: OffscreenCanvas; } | null;
  renderSplit(frame: number, at: number, override?: ((i: number) => Uint32Array | undefined) | undefined): OffscreenCanvas | null;
  savedLayers(): Layer[];
};
